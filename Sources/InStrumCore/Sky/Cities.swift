    /// The city for the Mac's time zone, or nil (for UTC, say) so the caller can fall back.
    public static func defaultCity(for zone: TimeZone) -> City? {
        let id = aliases[zone.identifier] ?? zone.identifier
        return all.first { $0.timeZoneID == id }
    }

