import Foundation

/// A city the Living Sky can follow in real time.
public struct City: Codable, Equatable, Identifiable {
    public let id: String
    public let name, country: String
    public let point: GeoPoint
    public let timeZoneID: String

    public init(id: String, name: String, country: String, point: GeoPoint, timeZoneID: String) {
        self.id = id; self.name = name; self.country = country; self.point = point; self.timeZoneID = timeZoneID
    }

    public var timeZone: TimeZone { TimeZone(identifier: timeZoneID) ?? .current }
}

/// About 230 cities on every inhabited continent (plus a few polar and island skies), with IANA time zones.
/// Within a time zone the first city listed is the one the app picks by default.
